"""Static recompiler driver: PS-X EXE (+ overlays) -> C sources.

    python tools/recomp/main.py [--exe extracted/SLUS_003.73] [--out generated]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from analysis import Analyzer, CodeImage, load_delay_hazards
from emit import FunctionEmitter
from psxexe import PsxExe

FUNCS_PER_FILE = 150


def load_extra_seeds(path: Path) -> set[int]:
    """Entry points the runtime found itself interpreting (see runtime/src/interp.cpp)."""
    if not path.exists():
        return set()
    seeds = set()
    for line in path.read_text().split():
        seeds.add(int(line, 16))
    return seeds


def analyze_main(exe: PsxExe, extra_seeds: set[int]) -> Analyzer:
    img = CodeImage(exe.text_addr, exe.text, "main")
    an = Analyzer(img)
    an.discover({exe.pc0} | {s for s in extra_seeds if img.contains(s)})
    an.discover(an.pointer_seeds())
    for _ in range(8):
        g = an.gap_seeds()
        if not g:
            break
        an.discover(g)
    return an


def write_if_changed(path: Path, text: str):
    # keeps unchanged generated files from triggering rebuilds
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)


def fnv1a(data: bytes) -> int:
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def emit_all(an: Analyzer, out: Path, prefix: str, debug_ra: bool, exe_info: list[str]) -> list[int]:
    out.mkdir(parents=True, exist_ok=True)
    fns = [an.functions[e] for e in sorted(an.functions)]
    known = set(an.functions)
    header = [
        "// Generated by tools/recomp. Do not edit.",
        "#pragma once",
        '#include "recomp.h"',
        "",
    ]
    header += [f"void {f.name}(R3000* c);" for f in fns]
    write_if_changed(out / f"{prefix}_funcs.h", "\n".join(header) + "\n")

    n_files = 0
    for start in range(0, len(fns), FUNCS_PER_FILE):
        chunk = fns[start : start + FUNCS_PER_FILE]
        parts = [
            "// Generated by tools/recomp. Do not edit.",
            f'#include "{prefix}_funcs.h"',
            "",
        ]
        for f in chunk:
            parts.append(FunctionEmitter(f, known, debug_ra).emit())
        write_if_changed(out / f"{prefix}_{n_files:03d}.c", "\n".join(parts))
        n_files += 1

    table = [
        "// Generated by tools/recomp. Do not edit.",
        f'#include "{prefix}_funcs.h"',
        "",
        f"const RecompFunc {prefix}_func_table[] = {{",
    ]
    table += [f"    {{0x{f.entry:08X}u, {f.name}}}," for f in fns]
    table += ["};", f"const uint32_t {prefix}_func_count = {len(fns)};", ""]
    table += exe_info
    write_if_changed(out / f"{prefix}_table.c", "\n".join(table))

    # stale chunk files from a previous run with more functions
    for p in out.glob(f"{prefix}_[0-9][0-9][0-9].c"):
        if int(p.stem.split("_")[-1]) >= n_files:
            p.unlink()
    return [f.entry for f in fns]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default="extracted/SLUS_003.73")
    ap.add_argument("--out", default="generated")
    ap.add_argument("--seeds", default="extra_seeds.txt",
                    help="extra function entry points, one hex address per line")
    ap.add_argument("--no-ra-check", action="store_true",
                    help="omit the debug check that jr ra returns to the caller")
    args = ap.parse_args()

    t0 = time.time()
    exe = PsxExe.load(args.exe)
    an = analyze_main(exe, load_extra_seeds(Path(args.seeds)))
    fns = an.functions
    errs = {e: f.errors for e, f in fns.items() if f.errors}
    hazards = {f.name: [hex(a) for a in load_delay_hazards(f)] for f in fns.values()}
    hazards = {k: v for k, v in hazards.items() if v}
    print(f"analysis: {len(fns)} functions, {sum(len(f.jump_tables) for f in fns.values())} "
          f"jump tables, {len(errs)} with errors, {len(hazards)} with load-delay hazards "
          f"({time.time() - t0:.1f}s)")
    if hazards:
        print("load-delay hazards are not modelled yet:", hazards, file=sys.stderr)
        sys.exit(1)

    out = Path(args.out)
    # lets the runtime refuse a disc whose EXE differs from the one recompiled
    exe_info = [
        f"const uint32_t main_exe_text_addr = 0x{exe.text_addr:08X}u;",
        f"const uint32_t main_exe_text_size = 0x{len(exe.text):X}u;",
        f"const uint32_t main_exe_hash = 0x{fnv1a(exe.text):08X}u;",
        "",
    ]
    entries = emit_all(an, out, "main", debug_ra=not args.no_ra_check, exe_info=exe_info)
    (out / "main_functions.json").write_text(json.dumps({
        "pc0": exe.pc0, "text_addr": exe.text_addr, "text_size": len(exe.text),
        "functions": entries, "errors": {f"{k:08X}": v for k, v in errs.items()},
    }, indent=1))
    print(f"emitted {len(entries)} functions to {out} ({time.time() - t0:.1f}s)")


if __name__ == "__main__":
    main()
